<?php
// Nik-Negar kit — installer and health check.
//   php install.php          install or repair (safe to run again; never deletes anything)
//   php install.php --check  only check, change nothing
// Without SSH: run it once from a one-minute cron job (see docs/PLAYBOOK.md); the result is written to install-report.txt.
declare(strict_types=1);

$CHECK = in_array('--check', $argv ?? [], true);
$rep = []; $bad = 0;
$ok = function (string $m) use (&$rep) { $rep[] = "✅ $m"; };
$no = function (string $m) use (&$rep, &$bad) { $rep[] = "❌ $m"; $bad++; };
$info = function (string $m) use (&$rep) { $rep[] = "   $m"; };
$finish = function () use (&$rep, &$bad, $CHECK) {
    $rep[] = $bad ? "\n$bad problem(s). Fix them and run again." : "\nAll good" . ($CHECK ? '.' : ' — installed.');
    $txt = implode("\n", $rep) . "\n";
    @file_put_contents(__DIR__ . '/install-report.txt', '[' . date('c') . "]\n" . $txt);
    echo $txt;
    exit($bad ? 1 : 0);
};

/* 1. PHP */
if (PHP_VERSION_ID < 80100) { $no('PHP 8.1+ needed, this is ' . PHP_VERSION); $finish(); }
$ok('PHP ' . PHP_VERSION);
foreach (['curl', 'dom', 'mbstring', 'gd', 'json'] as $e) extension_loaded($e) ? null : $no("PHP extension $e is missing");
if (extension_loaded('gd') && !function_exists('imagewebp')) $no('GD has no WebP support (covers need it)');
if ($bad) $finish();

/* 2. site.json */
if (!is_file(__DIR__ . '/site.json')) { $no('site.json missing — copy site.example.json to site.json and fill it in'); $finish(); }
$j = json_decode((string)file_get_contents(__DIR__ . '/site.json'), true);
if (!is_array($j)) { $no('site.json is not valid JSON: ' . json_last_error_msg()); $finish(); }
foreach (['site_name', 'url', 'public_html', 'content_repo', 'langs'] as $k) if (empty($j[$k])) $no("site.json: \"$k\" is empty");
if (!empty($j['url']) && !preg_match('#^https://[^/]+$#', rtrim($j['url'], '/'))) $no('site.json: "url" must look like https://example.com');
if (!empty($j['public_html']) && !is_dir($j['public_html'])) $no('site.json: public_html folder not found: ' . $j['public_html']);
elseif (!empty($j['public_html']) && !is_writable($j['public_html'])) $no('public_html is not writable by PHP');
if (!empty($j['content_repo']) && !preg_match('#^[\w.-]+/[\w.-]+$#', $j['content_repo'])) $no('site.json: "content_repo" must be owner/repo');
foreach ((array)($j['langs'] ?? []) as $i => $l)
    foreach (['code', 'base', 'author'] as $k) if (empty($l[$k])) $no("site.json: langs[$i].$k is empty");
if ($bad) $finish();
$ok('site.json (' . $j['site_name'] . ', ' . implode('+', array_column($j['langs'], 'code')) . ')');

/* 3. secrets */
if (!$CHECK && !is_file(__DIR__ . '/secrets.auto.php')) {
    $r = fn(int $n) => bin2hex(random_bytes($n));
    file_put_contents(__DIR__ . '/secrets.auto.php', "<?php\n// Generated by install.php. Keep private; never commit.\n"
        . "const HOOK_SECRET = '" . $r(16) . "';\nconst PANEL_DIR = 'tg-" . $r(6) . "';\nconst INDEXNOW_KEY = '" . $r(16) . "';\nconst OWNER_CLAIM = '" . $r(8) . "';\n");
    @chmod(__DIR__ . '/secrets.auto.php', 0600);
    $ok('secrets.auto.php generated (webhook secret, panel folder, IndexNow key, owner claim code)');
}
if (!is_file(__DIR__ . '/config.php')) { $no('config.php missing — copy config.example.php to config.php and paste the bot token'); $finish(); }
@chmod(__DIR__ . '/config.php', 0600);

require __DIR__ . '/core.php';
require_once __DIR__ . '/update.php';

if (TG_BOT_TOKEN === '' || str_contains(TG_BOT_TOKEN, 'PASTE') || !preg_match('/^\d+:[\w-]{30,}$/', TG_BOT_TOKEN)) $no('config.php: TG_BOT_TOKEN is not a bot token');
if (GH_TOKEN !== '' && !gh_can_write()) $no('config.php: GH_TOKEN does not look like a GitHub token (github_pat_… or ghp_…)');
if (GH_TOKEN === '') $info('GH_TOKEN is empty: drafts still arrive (public repo), but keyword editing and the "new article" button will not work');
if (!defined('OWNER_CLAIM')) $no('secrets.auto.php missing — run without --check once');
if ($bad) $finish();

/* 4. folders, templates, key file */
if (!$CHECK) {
    foreach (['state', 'logs', 'backups', 'drafts', 'rejected', 'inbox', 'templates'] as $d) @mkdir(AB . "/$d", 0700, true);
    foreach (langs() as $l) {
        foreach (["article-$l.html" => 'article.html', "index-$l.html" => 'index.html'] as $dst => $src)
            if (!is_file(AB . "/templates/$dst")) { copy(AB . "/templates-default/$src", AB . "/templates/$dst"); $info("templates/$dst ← default"); }
    }
    if (!is_file(AB . '/templates/card.html')) copy(AB . '/templates-default/card.html', AB . '/templates/card.html');
    if (INDEXNOW_KEY && !is_file(PUB . '/' . INDEXNOW_KEY . '.txt')) write_file(PUB . '/' . INDEXNOW_KEY . '.txt', INDEXNOW_KEY);
}
foreach (langs() as $l) foreach (["article-$l.html", "index-$l.html"] as $t) {
    $c = (string)@file_get_contents(AB . "/templates/$t");
    if ($c === '') { $no("templates/$t missing"); continue; }
    $need = str_starts_with($t, 'article') ? ['{{PROSE}}', '{{ROBOTS}}', '{{RELATED}}', '{{LD}}', '{{URL}}'] : ['{{CARDS}}', '{{ROBOTS}}'];
    foreach ($need as $p) if (!str_contains($c, $p)) $no("templates/$t has no $p");
}
if ($bad) $finish();
$ok('templates');

/* 5. blog pages per language */
foreach (langs() as $l) {
    $Lc = L($l);
    $idx = $Lc['dir'] . '/index.html';
    if (!$CHECK) {
        @mkdir($Lc['dir'], 0755, true);
        if (!is_file($idx)) { write_file($idx, render_index($l)); $info("{$Lc['base']} index created"); }
        write_sitemap($l);
        write_file($Lc['dir'] . '/feed.xml', build_feed($l));
    }
    $cur = (string)@file_get_contents($idx);
    if ($cur === '') $no("{$Lc['base']}index.html missing");
    elseif (substr_count($cur, '<!--nn:cards-->') !== 1) $no("{$Lc['base']}index.html must contain the <!--nn:cards--> … <!--/nn:cards--> markers exactly once, where the article cards go");
    else $ok("blog {$Lc['base']} (" . count(posts($l)) . ' posts)');
}

/* 6. robots.txt */
$robots = PUB . '/robots.txt';
$rt = (string)@file_get_contents($robots);
$add = '';
foreach (langs() as $l) { $u = SITE . L($l)['base'] . 'sitemap-blog.xml'; if (!str_contains($rt, $u)) $add .= "Sitemap: $u\n"; }
if ($add !== '') {
    if ($CHECK) $no('robots.txt does not list the blog sitemaps');
    else { write_file($robots, rtrim($rt) . ($rt === '' ? "User-agent: *\nAllow: /\n" : '') . "\n" . $add); $ok('robots.txt: blog sitemaps added'); }
} else $ok('robots.txt lists the blog sitemaps');

/* 7. panel + webhook */
if (!$CHECK) { $p = install_panel(); $p === true ? $ok('panel installed in /' . PANEL_DIR . '/') : $no("panel: $p"); }
$me = tg('getMe', []);
if (!$me) { $no(messenger_name() . ' rejected the bot token (getMe failed)'); $finish(); }
$bot = $me['result']['username'];
$ok(messenger_name() . " bot @$bot");
$hook = SITE . '/' . PANEL_DIR . '/hook.php';
if (!$CHECK) {
    $w = messenger() === 'bale'
        ? tg('setWebhook', ['url' => $hook . '?k=' . HOOK_SECRET])          // Bale: no secret header, the secret rides in the URL
        : tg('setWebhook', ['url' => $hook, 'secret_token' => HOOK_SECRET, 'allowed_updates' => ['message', 'callback_query'], 'drop_pending_updates' => false]);
    $w ? $ok('webhook set') : $no('setWebhook failed (is the site on valid HTTPS?)');
    with_state(function (array &$s) { $s['webhook'] = true; }, 30);
    tg('setMyCommands', ['commands' => [
        ['command' => 'status', 'description' => 'وضعیت نیک‌نگار'], ['command' => 'settings', 'description' => 'تنظیمات انتشار'],
        ['command' => 'write', 'description' => 'نوشتن مقاله‌ی جدید'], ['command' => 'publishnow', 'description' => 'انتشار فوری مقاله‌ی بعدی صف'],
        ['command' => 'members', 'description' => 'اعضا و دسترسی‌ها']]]);
    tg('setChatMenuButton', ['menu_button' => ['type' => 'web_app', 'text' => 'نیک‌نگار', 'web_app' => ['url' => panel_url()]]]);
    tg('setMyDescription', ['description' => 'نیک‌نگار — میز تحریریه‌ی بلاگ ' . site('site_name') . ". ربات خصوصی است.\nطراحی و ساخت: دکتر محمدرضا نظیف"]);
    tg('setMyShortDescription', ['short_description' => 'میز تحریریه‌ی بلاگ ' . site('site_name')]);
}
$wi = tg('getWebhookInfo', []);
$wurl = $wi['result']['url'] ?? '';
strtok($wurl, '?') === $hook ? $ok('webhook points here' . (!empty($wi['result']['last_error_message']) ? ' (last error: ' . $wi['result']['last_error_message'] . ')' : ''))
                : $no("webhook is '$wurl', expected $hook");
$panel = http(panel_url() . '?t=' . time());
$panel['code'] === 200 && str_contains($panel['body'], 'telegram-web-app') ? $ok('panel page is reachable') : $no('panel page did not load (' . $panel['code'] . ')');

/* 8. GitHub content repo */
$g = gh_api('GET', '');
if ($g['code'] !== 200) $no('content repo ' . GITHUB_REPO . ' not reachable (' . $g['code'] . ')' . (GH_TOKEN === '' ? ' — private repos need GH_TOKEN' : ''));
else {
    $ok('content repo ' . GITHUB_REPO . (empty($g['json']['private']) ? ' (public)' : ' (private)'));
    if (gh_can_write()) !empty($g['json']['permissions']['push']) ? $ok('GH_TOKEN can push') : $no('GH_TOKEN cannot push to the content repo (needs Contents: read and write)');
    $t = gh_api('GET', '/contents/topics.json?ref=main');
    $t['code'] === 200 ? $ok('topics.json found') : $no('topics.json not found in the content repo');
}

/* 9. cover photos */
$ov = openverse_search('city street');
$ov ? $ok('Openverse photos reachable') : $no('Openverse search failed (covers will be skipped)');

/* 10. next steps */
$s = state_load();
$rep[] = '';
$rep[] = 'cron (every minute):  * * * * *  cd ' . AB . ' && ' . PHP_BINARY . ' run.php >> logs/cron.txt 2>&1';
if (!$s['chat_ids']) $rep[] = messenger() === 'bale'
    ? "OWNER: open the bot @$bot in Bale and send exactly this message (the first person to do it becomes the owner):\n       /start " . OWNER_CLAIM
    : "OWNER: open this link in Telegram and press Start — the first person to do it becomes the owner:\n       https://t.me/$bot?start=" . OWNER_CLAIM;
else $rep[] = 'owner: ' . member_name($s, owner_id($s)) . ' · members: ' . count($s['chat_ids']);
$finish();
